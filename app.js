function formatMoney(value) {
  if (!Number.isFinite(value)) return localizeValue("Manual review");
  if (value >= 1000000) return `$${(value / 1000000).toFixed(3).replace(/0+$/, "").replace(/\.$/, "")}m`;
  return `$${Math.round(value / 1000)}k`;
}

